
module led_ctrl
   (
    //--
    input                               rst_n                   ,   
    input                               clk                     ,  
    //***********************************************************
    //DDR Test
    //***********************************************************
    input                               init_calib_complete     ,   
    input                               tg_compare_error        ,   
    output   reg[ 1:0]                  led                        
   );
//*******************************************************************
//--
//*******************************************************************
reg[27:0]                       cnt                                 ; 
reg                             led_r                               ;   
//*******************************************************************
//--1S Time 
//*******************************************************************
always @ (posedge clk or negedge rst_n)begin
   if(!rst_n)
      cnt <= 28'd0;
   else if(cnt == 28'd50000000) //--50Mhz 1s 钟循环计数
      cnt <= 28'b0;
   else
      cnt <= cnt + 1'b1;
end
//*******************************************************************
//--1s 钟循环控制
//*******************************************************************
always @ (posedge clk or negedge rst_n)begin
   if(!rst_n)
      led_r <= 1'b0;
   else if(cnt == 28'd50000000)
      led_r <= ~led_r;
end
//*******************************************************************
//--LED0
//*******************************************************************
always @ (*)begin
    led[0] = led_r;
end
//*******************************************************************
//--LED1
//*******************************************************************
always @ (*)begin
   if(init_calib_complete==1'b1)begin
      if(tg_compare_error==1'b0)
        led[1] = ~led_r;//初始化成功 自检正确
      else
        led[1] = 1'b1;  //初始化成功 自检错误
      end  
   else
      led[1] = 1'b0;    //初始化错误
end
endmodule

