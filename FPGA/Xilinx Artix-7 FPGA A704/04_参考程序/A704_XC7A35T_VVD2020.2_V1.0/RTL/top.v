

module top
   (
      //***********************************************************
      //--Clock 
      //***********************************************************
      input                               sys_clk                 , 
      //***********************************************************
      //--DDR3 Interface
      //***********************************************************
      // Inouts
      inout         [15:0]                ddr3_dq                 ,   
      inout         [1:0]                 ddr3_dqs_n              ,   
      inout         [1:0]                 ddr3_dqs_p              ,   
      // Outputs
      output        [14:0]                ddr3_addr               ,   
      output        [2:0]                 ddr3_ba                 ,   
      output                              ddr3_ras_n              ,   
      output                              ddr3_cas_n              ,   
      output                              ddr3_we_n               ,   
      output                              ddr3_reset_n            ,   
      output        [0:0]                 ddr3_ck_p               ,   
      output        [0:0]                 ddr3_ck_n               ,     
      output        [0:0]                 ddr3_cke                ,   
      output        [1:0]                 ddr3_dm                 ,   
      output        [0:0]                 ddr3_odt                ,
      //***********************************************************
      //--KEY
      //***********************************************************
      input                               key                     , //  Low Active 
      //***********************************************************
      //--LED
      //***********************************************************
      output        [1:0]                 led                     ,
      //***********************************************************
      //--UART
      //***********************************************************
      input                               rxd                     ,                             
      output                              txd                     ,
      //***********************************************************
      //--IO
      //***********************************************************
      output        [IO_NUM-1:0]          o_sig                                      
     );

//*******************************************************************
//--
//*******************************************************************
parameter      IO_NUM             =   161                           ;                     

assign         sys_rst_n          =   1'b1                          ;

//*******************************************************************
//--
//*******************************************************************
wire                            clk_200M                            ;  
wire                            clk_50M                             ; 
wire                            ddr3_clk                            ;
(* MARK_DEBUG="true" *)
wire       [1:0]                clk_locked                          ;    
wire                            rst_n                               ; 
//*******************************************************************
//--DDR3
//*******************************************************************
(* MARK_DEBUG="true" *)
wire                            init_calib_complete                 ; 
(* MARK_DEBUG="true" *)
wire                            tg_compare_error                    ;   
(* MARK_DEBUG="true" *)
wire      [47:0]                tg_wr_data_counts                   ;
(* MARK_DEBUG="true" *)
wire      [47:0]                tg_rd_data_counts                   ; 
wire      [11:0]                device_temp                         ;   
//***********************************************************
//--Clock Ctrl
//***********************************************************
clk_ctrl UU1 (
    .clk                        (sys_clk                    ),
    .rst_n                      (sys_rst_n                  ),
    //*******************************************************
    //--
    //*******************************************************
    .clk_200M                   (clk_200M                   ),
    .clk_50M                    (clk_50M                    ),
    .ddr3_clk                   (ddr3_clk                   ), 
    //*******************************************************
    //Clock Locked
    //*******************************************************
    .clk_locked                 (clk_locked                 )
    );   

//***********************************************************
//--Reset Ctrl
//***********************************************************
rst_ctrl UU2 (
    .sys_clk                    (clk_50M                    ),
    .sys_rst_n                  (sys_rst_n                  ),
    .clk_locked                 (clk_locked                 ), 
    //*******************************************************
    //--
    //*******************************************************
    .rst_n                      (rst_n                      )
    );

//***********************************************************
//DDR3
//***********************************************************
example_top UU3
     (
    .ddr3_dq                    (ddr3_dq                    ),
    .ddr3_dqs_n                 (ddr3_dqs_n                 ),
    .ddr3_dqs_p                 (ddr3_dqs_p                 ),
    .ddr3_addr                  (ddr3_addr                  ),
    .ddr3_ba                    (ddr3_ba                    ),
    .ddr3_ras_n                 (ddr3_ras_n                 ),
    .ddr3_cas_n                 (ddr3_cas_n                 ),
    .ddr3_we_n                  (ddr3_we_n                  ),
    .ddr3_reset_n               (ddr3_reset_n               ),
    .ddr3_ck_p                  (ddr3_ck_p                  ),
    .ddr3_ck_n                  (ddr3_ck_n                  ),
    .ddr3_cke                   (ddr3_cke                   ),
    .ddr3_dm                    (ddr3_dm                    ),
    .ddr3_odt                   (ddr3_odt                   ),
    .sys_clk_i                  (ddr3_clk                   ),
    .clk_ref_i                  (clk_200M                   ),
    .init_calib_complete        (init_calib_complete        ),
    .tg_compare_error           (tg_compare_error           ),
    .tg_wr_data_counts          (tg_wr_data_counts          ),
    .tg_rd_data_counts          (tg_rd_data_counts          ),
    .device_temp_i              (device_temp                ),
    .sys_rst                    (rst_n                      )
     );
//***********************************************************
//--LED
//***********************************************************
led_ctrl UU4(
    .rst_n                      (rst_n                      ),
    .clk                        (clk_50M                    ), 
    //*******************************************************
    //DDR Test
    //*******************************************************
    .init_calib_complete        (init_calib_complete        ),
    .tg_compare_error           (tg_compare_error           ),
    .led                        (led                        )
    );
//*******************************************************************
//XADC
//*******************************************************************
xadc_temp UU5 
(
    .clk                        (clk_50M                    ),
    .xadc_clk                   (clk_200M                   ),
    .rst                        (~rst_n                     ),
    .device_temp                (device_temp                )
);
//***********************************************************
//--UART
//***********************************************************     
uart_top UU6 (
    .rst_n                      (rst_n                      ),
    .clk                        (clk_50M                    ), 
    //*******************************************************
    //DDR Test
    //*******************************************************
    .init_calib_complete        (init_calib_complete        ),
    .tg_compare_error           (tg_compare_error           ),
    .w_code_rate                (tg_wr_data_counts          ),
    .r_code_rate                (tg_rd_data_counts          ),
    //*******************************************************
    //--Temp
    //*******************************************************
    .device_temp                (device_temp                ),
    //*******************************************************
    //LED Test
    //*******************************************************
    .led                        (led                        ),
    //*******************************************************
    //--KEY 
    //*******************************************************
    .key                        (key                        ),
    //*******************************************************
    //--UART
    //*******************************************************
    .uart_rxd                   (rxd                        ),
    .uart_txd                   (txd                        )
    );
//***********************************************************
//--IO Test
//***********************************************************
io_test UU7(
    .rst_n                      (rst_n                      ),
    .clk                        (clk_50M                    ), 
    .io_sig                     (io_sig                     )
    );
assign o_sig = {IO_NUM{io_sig}};

endmodule


